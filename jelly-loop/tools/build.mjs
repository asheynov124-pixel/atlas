// node tools/build.mjs
//
// 1. Deals a hand for every picture in levels.mjs and proves with a bot that it can be won.
//    Writes src/levels.js.
// 2. Minifies src/ into dist/, which is the folder that gets deployed.

import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { minify } from 'terser';
import { PICTURES } from './levels.mjs';
import { PUZZLES } from './puzzles.mjs';

const require = createRequire(import.meta.url);
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const Deal = require(path.join(root, 'src/deal.js'));

function buildLevel(pic, index) {
  const w = pic.art[0].length;
  for (const row of pic.art) if (row.length !== w) throw new Error(pic.name + ': ragged row ' + row);
  if (pic.bg) pic.art = pic.art.map((row) => row.replace(/\./g, pic.bg));
  pic.chunk = Deal.jellyChunk(pic.chunk, index);
  const jellies = Deal.jelliesFor(pic.art, pic.chunk);
  // Deal a hand, prove it winnable with the careful bot, and keep the hand whose loss rate
  // for a careless player is closest to the target for this level's mix.
  const chosen = Deal.level(pic, index, { trials: 30 });
  if (!chosen) throw new Error(pic.name + ': no winnable hand found');
  const cubes = pic.art.join('').replace(/[.#]/g, '').length;
  console.log(
    String(index + 1).padStart(2) + '. ' + pic.name.padEnd(16) +
    (w + 'x' + pic.art.length).padEnd(7) + String(cubes).padStart(4) + ' cubes  ' +
    String(jellies.length).padStart(2) + ' jellies  bot wins in ' + chosen.seconds.toFixed(0).padStart(3) +
    's  jelly size ' + String(pic.chunk).padStart(2) + '  careless play loses ' + String(Math.round(chosen.rate * 100)).padStart(3) + '%  par ' + chosen.level.par + 's' +
    (pic.boss ? '  BOSS' : '') + (pic.locks ? '  ' + pic.locks + ' chained' : '')
  );
  if (pic.intro) chosen.level.intro = pic.intro;
  if ((index % 10 === 9) !== !!pic.boss) throw new Error(pic.name + ': every tenth level, and only those, must be a boss');
  return chosen.level;
}

function buildPuzzle(pic, index) {
  const w = pic.art[0].length;
  for (const row of pic.art) if (row.length !== w) throw new Error(pic.name + ': ragged row ' + row);
  const got = Deal.puzzle(pic, index, 16);
  if (!got) throw new Error(pic.name + ': no puzzle hand found');
  console.log('P' + String(index + 1).padStart(2) + '. ' + pic.name.padEnd(14) + String(got.level.moves).padStart(2) + ' sends  random play solves ' + String(Math.round(got.odds * 100)).padStart(3) + '%');
  got.level.odds = got.odds;
  return got.level;
}

const obj = (o) => '{ ' + Object.entries(o).map(([k, v]) => k + ': ' + v).join(', ') + ' }';
const levelLine = (l) =>
  "  { name: '" + l.name + "'" + (l.par ? ', par: ' + l.par : '') + (l.intro ? ", intro: '" + l.intro + "'" : '') +
  (l.boss ? ', boss: ' + obj(l.boss) : '') + (l.keys ? ', keys: [' + l.keys.join(', ') + ']' : '') +
  (l.moves ? ', seats: ' + l.seats + ', belt: ' + l.belt + ', moves: ' + l.moves : '') +
  ",\n    art: [" + l.art.map((r) => "'" + r + "'").join(', ') +
  '],\n    hand: [' + l.hand.map((h) => "'" + h + "'").join(', ') + '] }';

// ---------- build ----------

const levels = PICTURES.map(buildLevel);
console.log('');
// Puzzles go from easy to hard: the first one teaches, the rest by how rarely random play wins.
const built = PUZZLES.map(buildPuzzle);
const puzzles = [built[0]].concat(built.slice(1).sort((a, b) => b.odds - a.odds));
const levelsJs =
  '// Generated by tools/build.mjs from tools/levels.mjs and tools/puzzles.mjs. Do not edit by hand.\n' +
  'var LEVELS = [\n' + levels.map(levelLine).join(',\n') + '\n];\n' +
  'var PUZZLES = [\n' + puzzles.map(levelLine).join(',\n') + '\n];\n';
fs.writeFileSync(path.join(root, 'src/levels.js'), levelsJs);

const dist = path.join(root, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(path.join(dist, 'icons'), { recursive: true });

const scripts = ['core.js', 'levels.js', 'deal.js', 'render.js', 'home.js', 'app.js', 'sw.js'].filter((f) => fs.existsSync(path.join(root, 'src', f)));
for (const f of scripts) {
  const out = await minify(fs.readFileSync(path.join(root, 'src', f), 'utf8'), {
    compress: { passes: 2 },
    mangle: true,
    format: { quote_style: 1, comments: false }
  });
  fs.writeFileSync(path.join(dist, f), out.code);
}

// HTML: one line, tags only ever break between elements in the source.
if (fs.existsSync(path.join(root, 'src/index.html'))) {
  const html = fs.readFileSync(path.join(root, 'src/index.html'), 'utf8')
    .split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('<!--')).join('')
    .replace(/\s*([{};:,>])\s*(?=[^<]*<\/style>)/g, '$1');
  fs.writeFileSync(path.join(dist, 'index.html'), html);
}
for (const f of ['manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png']) {
  if (fs.existsSync(path.join(root, 'src', f))) fs.copyFileSync(path.join(root, 'src', f), path.join(dist, f));
}

// The deploy step pastes these files into a JSON request, so keep them free of
// characters that would need escaping there.
console.log('\ndist/');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
for (const file of walk(dist).sort()) {
  const buf = fs.readFileSync(file);
  const rel = path.relative(dist, file);
  const sha = crypto.createHash('sha1').update(buf).digest('hex');
  let note = '';
  if (/\.(js|html)$/.test(rel)) {
    const s = buf.toString('utf8');
    const bad = [];
    if (s.includes('"')) bad.push('double quote');
    if (s.includes('\\')) bad.push('backslash');
    if (/[\r\n]/.test(s)) bad.push('newline');
    if (/[^\x20-\x7e]/.test(s)) bad.push('non-ASCII');
    if (bad.length) note = '  <-- contains ' + bad.join(', ');
  }
  console.log('  ' + rel.padEnd(28) + String(buf.length).padStart(6) + ' bytes  ' + sha + note);
}

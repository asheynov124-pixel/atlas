#!/usr/bin/env bash
# MediaVault installer for Linux / macOS.
# Downloads the official Stash release, verifies its SHA1 against the release's
# CHECKSUMS_SHA1 file, lays out a private library, and writes a localhost-only config.
#
#   ./install.sh                       # installs into ~/MediaVault, latest Stash
#   ./install.sh --root /Volumes/Vault # install onto an encrypted volume
#   STASH_VERSION=v0.32.0 ./install.sh # pin a version
set -euo pipefail

ROOT="${HOME}/MediaVault"
PORT=9999
VERSION="${STASH_VERSION:-latest}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --root) ROOT="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --version) VERSION="$2"; shift 2 ;;
    -h|--help) sed -n 2,9p "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
done

if [[ "$VERSION" == "latest" ]]; then
  BASE="https://github.com/stashapp/stash/releases/latest/download"
else
  BASE="https://github.com/stashapp/stash/releases/download/${VERSION}"
fi

os="$(uname -s)"; arch="$(uname -m)"
case "$os/$arch" in
  Linux/x86_64)            ASSET=stash-linux ;;
  Linux/aarch64|Linux/arm64) ASSET=stash-linux-arm64v8 ;;
  Linux/armv7l)            ASSET=stash-linux-arm32v7 ;;
  Linux/armv6l)            ASSET=stash-linux-arm32v6 ;;
  Darwin/*)                ASSET=stash-macos ;;   # universal binary
  FreeBSD/*)               ASSET=stash-freebsd ;;
  *) echo "unsupported platform: $os/$arch" >&2; exit 1 ;;
esac

need() { command -v "$1" >/dev/null 2>&1 || { echo "missing dependency: $1" >&2; exit 1; }; }
need curl
if command -v sha1sum >/dev/null; then SHA1="sha1sum"; else need shasum; SHA1="shasum -a 1"; fi

echo "==> Layout under $ROOT"
mkdir -p "$ROOT"/{bin,staging,library/{videos,images,vr},stash/{generated,cache,blobs,scrapers,plugins,backups}}

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
echo "==> Downloading $ASSET ($VERSION)"
curl -fsSL -o "$tmp/$ASSET" "$BASE/$ASSET"
curl -fsSL -o "$tmp/CHECKSUMS_SHA1" "$BASE/CHECKSUMS_SHA1"

expected="$(awk -v a="$ASSET" '$2==a {print $1; exit}' "$tmp/CHECKSUMS_SHA1")"
actual="$($SHA1 "$tmp/$ASSET" | awk '{print $1}')"
if [[ -z "$expected" || "$expected" != "$actual" ]]; then
  echo "CHECKSUM MISMATCH for $ASSET (expected '$expected', got '$actual'). Aborting." >&2
  exit 1
fi
echo "    sha1 OK: $actual"

install -m 0755 "$tmp/$ASSET" "$ROOT/bin/stash"
[[ "$os" == "Darwin" ]] && xattr -d com.apple.quarantine "$ROOT/bin/stash" 2>/dev/null || true
"$ROOT/bin/stash" --version

CONFIG="$ROOT/stash/config.yml"
if [[ -f "$CONFIG" ]]; then
  echo "==> Keeping existing $CONFIG"
else
  echo "==> Writing $CONFIG (localhost-only)"
  cat > "$CONFIG" <<EOF
# Stash config generated by MediaVault install.sh
# host 127.0.0.1 = reachable only from this machine. Change to 0.0.0.0 for LAN
# access, and set a username/password first (Settings > Security).
host: 127.0.0.1
port: ${PORT}
stash:
  - path: ${ROOT}/library
    excludeVideo: false
    excludeImage: false
database: ${ROOT}/stash/stash-go.sqlite
generated: ${ROOT}/stash/generated
cache: ${ROOT}/stash/cache
blobs_path: ${ROOT}/stash/blobs
blobs_storage: FILESYSTEM
scrapers_path: ${ROOT}/stash/scrapers
plugins_path: ${ROOT}/stash/plugins
backup_directory_path: ${ROOT}/stash/backups
calculate_md5: false
video_file_naming_algorithm: OSHASH
create_galleries_from_folders: true
parallel_tasks: 0
# never auto-open a browser; never leave the box
nobrowser: true
EOF
fi

LAUNCHER="$ROOT/start-stash.sh"
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Start Stash with the MediaVault config. Ctrl+C to stop.
exec "$ROOT/bin/stash" --config "$CONFIG" --nobrowser
EOF
chmod +x "$LAUNCHER"

cat <<EOF

Done.
  Start:    $LAUNCHER
  Open:     http://127.0.0.1:${PORT}
  Library:  $ROOT/library   (drop files here, or use ingest.py)
  Staging:  $ROOT/staging   (downloads land here before they are filed)

First-run checklist (in the web UI):
  1. Settings > Security: set a username + password, then generate an API key.
  2. Put the API key in media-library/.env as STASH_API_KEY=...
  3. Settings > Metadata Providers: add StashDB / ThePornDB / FansDB stash-box endpoints.
  4. Settings > Metadata Providers > Available Scrapers: install what you need.
EOF
command -v ffmpeg >/dev/null || echo "Note: ffmpeg not on PATH. Stash will download its own on first run."

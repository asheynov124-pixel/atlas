# MediaVault installer for Windows (PowerShell 5+).
# Downloads the official Stash release, verifies SHA1 against CHECKSUMS_SHA1,
# lays out a private library, and writes a localhost-only config.
#
#   powershell -ExecutionPolicy Bypass -File .\install.ps1
#   powershell -ExecutionPolicy Bypass -File .\install.ps1 -Root V:\MediaVault   # e.g. a VeraCrypt/BitLocker volume
param(
  [string]$Root = "$env:USERPROFILE\MediaVault",
  [int]$Port = 9999,
  [string]$Version = "latest"
)
$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$base = if ($Version -eq "latest") { "https://github.com/stashapp/stash/releases/latest/download" }
        else { "https://github.com/stashapp/stash/releases/download/$Version" }
$asset = "stash-win.exe"

Write-Host "==> Layout under $Root"
foreach ($d in "bin","staging","library\videos","library\images","library\vr",
               "stash\generated","stash\cache","stash\blobs","stash\scrapers","stash\plugins","stash\backups") {
  New-Item -ItemType Directory -Force -Path (Join-Path $Root $d) | Out-Null
}

$tmp = Join-Path $env:TEMP ("mediavault-" + [guid]::NewGuid())
New-Item -ItemType Directory -Path $tmp | Out-Null
try {
  Write-Host "==> Downloading $asset ($Version)"
  Invoke-WebRequest "$base/$asset" -OutFile "$tmp\$asset"
  Invoke-WebRequest "$base/CHECKSUMS_SHA1" -OutFile "$tmp\CHECKSUMS_SHA1"
  $expected = (Get-Content "$tmp\CHECKSUMS_SHA1" | Where-Object { $_ -match "\s$([regex]::Escape($asset))$" }) -split "\s+" | Select-Object -First 1
  $actual = (Get-FileHash "$tmp\$asset" -Algorithm SHA1).Hash.ToLower()
  if (-not $expected -or $expected -ne $actual) { throw "CHECKSUM MISMATCH for $asset (expected '$expected', got '$actual')" }
  Write-Host "    sha1 OK: $actual"
  Copy-Item "$tmp\$asset" (Join-Path $Root "bin\stash.exe") -Force
} finally { Remove-Item -Recurse -Force $tmp }

& (Join-Path $Root "bin\stash.exe") --version

$config = Join-Path $Root "stash\config.yml"
$fwd = $Root -replace "\\","/"   # YAML-friendly paths
if (Test-Path $config) { Write-Host "==> Keeping existing $config" } else {
  Write-Host "==> Writing $config (localhost-only)"
  @"
# Stash config generated by MediaVault install.ps1
# host 127.0.0.1 = reachable only from this PC. Set a password before opening it to the LAN.
host: 127.0.0.1
port: $Port
stash:
  - path: $fwd/library
    excludeVideo: false
    excludeImage: false
database: $fwd/stash/stash-go.sqlite
generated: $fwd/stash/generated
cache: $fwd/stash/cache
blobs_path: $fwd/stash/blobs
blobs_storage: FILESYSTEM
scrapers_path: $fwd/stash/scrapers
plugins_path: $fwd/stash/plugins
backup_directory_path: $fwd/stash/backups
calculate_md5: false
video_file_naming_algorithm: OSHASH
create_galleries_from_folders: true
parallel_tasks: 0
nobrowser: true
"@ | Set-Content -Encoding UTF8 $config
}

$launcher = Join-Path $Root "start-stash.cmd"
"@echo off`r`n`"$Root\bin\stash.exe`" --config `"$config`" --nobrowser" | Set-Content -Encoding ASCII $launcher

Write-Host ""
Write-Host "Done."
Write-Host "  Start:   $launcher"
Write-Host "  Open:    http://127.0.0.1:$Port"
Write-Host "  Library: $Root\library"
Write-Host "Then: Settings > Security (password + API key), Settings > Metadata Providers (StashDB/TPDB)."
Write-Host "Windows Firewall may ask about stash.exe - choose 'Cancel'/deny; localhost needs no firewall rule."
